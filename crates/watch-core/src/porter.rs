//! Porters: what actually prepares the Rust side for a new upstream version inside the RPoem clone.
//!  - `plan` (default): writes a porting plan under `docs/upstream/<name>/<version>.md` (docs only, safe to merge).
//!  - `command`: runs an external command in the clone (for example Claude Code in headless mode). Whatever it
//!    changes still has to pass the merge gate and the tests.

use crate::analysis::Assessment;
use crate::config::{Pin, PorterConfig, Upstream};
use crate::version::format_version;
use crate::github::Release;
use crate::services::Hit;
use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Clone)]
pub struct JobContext {
    pub upstream: Upstream,
    pub from: Option<String>,
    pub to: String,
    pub release: Release,
    pub hits: Vec<Hit>,
    pub ai_summary: Option<String>,
    pub assessment: Assessment,
    pub generated_on: String,
}

/// Keeps upstream text from breaking out of the code fence it is embedded in.
fn fence_safe(s: &str) -> String {
    s.replace("```", "'''")
}

fn truncate(s: &str, n: usize) -> String {
    if s.chars().count() <= n {
        s.to_string()
    } else {
        s.chars().take(n).collect::<String>() + "\n… (truncated)"
    }
}

pub fn plan_path(ctx: &JobContext) -> PathBuf {
    PathBuf::from("docs").join("upstream").join(&ctx.upstream.name).join(format!("{}.md", ctx.to))
}

pub fn render_plan(ctx: &JobContext) -> String {
    let mut s = String::new();
    s.push_str(&format!("# {} {} — porting plan\n\n", ctx.upstream.name, ctx.to));
    s.push_str(&format!("*Generated by open-upstream-watch on {}. Review before relying on it.*\n\n", ctx.generated_on));
    s.push_str(&format!("- Upstream: https://github.com/{}\n", ctx.upstream.repo));
    s.push_str(&format!("- Release: {}\n", if ctx.release.url.is_empty() { &ctx.release.tag } else { &ctx.release.url }));
    s.push_str(&format!("- Previous version seen: {}\n", ctx.from.as_deref().unwrap_or("(none, first detection)")));
    if !ctx.upstream.area.is_empty() {
        s.push_str(&format!("- RPoem area that re-implements it: `{}`\n", ctx.upstream.area));
    }
    s.push_str("\n## Release notes (verbatim from upstream)\n\n```text\n");
    let body = if ctx.release.body.trim().is_empty() { "(the release has no notes)".to_string() } else { fence_safe(&truncate(&ctx.release.body, 6000)) };
    s.push_str(&body);
    s.push_str("\n```\n");
    if !ctx.hits.is_empty() {
        s.push_str("\n## Related pages (aruaru-search)\n\n");
        for h in &ctx.hits {
            s.push_str(&format!("- [{}]({}) — {}\n", fence_safe(&h.title).replace(['[', ']'], ""), h.link, fence_safe(&h.snippet).replace('\n', " ")));
        }
    }
    if let Some(a) = &ctx.ai_summary {
        s.push_str("\n## Machine summary (aruaru-llm, unverified)\n\n> Low-reliability text from a small local model; check it against the release notes above.\n\n```text\n");
        s.push_str(&fence_safe(&truncate(a, 800)));
        s.push_str("\n```\n");
    }
    s.push_str("\n## Checklist\n\n- [ ] Read the release notes for breaking changes\n- [ ] Compare the public API / behaviour that RPoem mirrors\n- [ ] Update the compatibility notes (`docs/*-parity.md`) and the implementation if needed\n- [ ] Run the RPoem tests\n");
    s
}

/// Writes the plan file into the clone.
pub fn write_plan(clone: &Path, ctx: &JobContext) -> Result<PathBuf> {
    let rel = plan_path(ctx);
    let abs = clone.join(&rel);
    if let Some(d) = abs.parent() {
        std::fs::create_dir_all(d)?;
    }
    std::fs::write(&abs, render_plan(ctx))?;
    Ok(rel)
}

/// Rewrites the version captured by `pin.pattern` in `pin.file`. Returns whether the file changed.
pub fn apply_pin(clone: &Path, pin: &Pin, to: &str) -> Result<bool> {
    let path = clone.join(&pin.file);
    let text = std::fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
    let re = regex::Regex::new(&pin.pattern).context("bad pin pattern")?;
    let caps = re.captures(&text).with_context(|| format!("the pin pattern was not found in {}", pin.file))?;
    let m = caps.get(1).context("the pin pattern has no capture group")?;
    let new = format_version(to, &pin.format);
    if m.as_str() == new {
        return Ok(false);
    }
    let mut out = String::with_capacity(text.len());
    out.push_str(&text[..m.start()]);
    out.push_str(&new);
    out.push_str(&text[m.end()..]);
    std::fs::write(&path, out)?;
    Ok(true)
}

pub fn run_porter(cfg: &PorterConfig, clone: &Path, ctx: &JobContext) -> Result<()> {
    if let Some(pin) = &ctx.upstream.pin {
        apply_pin(clone, pin, &ctx.to)?;
        return Ok(());
    }
    match cfg.kind.as_str() {
        "plan" => {
            write_plan(clone, ctx)?;
            Ok(())
        }
        "command" => {
            let cmd = cfg.command.as_deref().context("porter.command is missing")?;
            // the prompt lives outside the clone so it never shows up as a change
            let prompt = std::env::temp_dir().join(format!("ouw-prompt-{}-{}.md", ctx.upstream.name, ctx.to));
            std::fs::write(&prompt, render_plan(ctx) + "\nTask: port the changes above to the Rust implementation in this repository. Keep changes minimal, add tests, do not touch CI, secrets or unrelated files.\n")?;
            let mut c = if cfg!(windows) {
                let mut c = Command::new("cmd");
                c.args(["/C", cmd]);
                c
            } else {
                let mut c = Command::new("sh");
                c.args(["-c", cmd]);
                c
            };
            let out = c
                .current_dir(clone)
                .env("UPSTREAM", &ctx.upstream.name)
                .env("VERSION", &ctx.to)
                .env("FROM", ctx.from.clone().unwrap_or_default())
                .env("RELEASE_URL", &ctx.release.url)
                .env("PROMPT_FILE", &prompt)
                .output()
                .with_context(|| format!("running porter command: {cmd}"))?;
            let _ = std::fs::remove_file(&prompt);
            if !out.status.success() {
                bail!("porter command failed: {}", String::from_utf8_lossy(&out.stderr).trim());
            }
            Ok(())
        }
        other => bail!("unknown porter kind {other}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ctx(body: &str) -> JobContext {
        JobContext {
            upstream: Upstream { name: "poem".into(), repo: "poem-web/poem".into(), tag_prefix: None, kind: "release".into(), area: "crates/open-runo-poem-compat".into(), mode: "port".into(), target: "rpoem".into(), pin: None },
            from: Some("3.1.0".into()),
            to: "3.2.0".into(),
            release: Release { tag: "v3.2.0".into(), name: "v3.2.0".into(), body: body.into(), url: "https://github.com/poem-web/poem/releases/tag/v3.2.0".into(), published_at: None },
            hits: vec![Hit { title: "Poem [3.2]".into(), link: "https://example.org/x".into(), snippet: "notes\nline".into() }],
            ai_summary: Some("A short machine summary".into()),
            assessment: Assessment::default(),
            generated_on: "2026-10-19".into(),
        }
    }

    #[test]
    fn plan_contains_the_facts_and_cannot_break_out_of_its_fence() {
        let p = render_plan(&ctx("fixes\n```\n# injected heading\n```"));
        assert!(p.contains("poem 3.2.0"));
        assert!(p.contains("crates/open-runo-poem-compat"));
        assert!(p.contains("unverified"));
        assert!(!p.contains("```\n# injected heading"), "the upstream text must not close the fence");
    }

    #[test]
    fn pin_rewrites_only_the_captured_version() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(dir.path().join("src")).unwrap();
        std::fs::write(dir.path().join("src/catalog.ts"), "a
leptos = { version = \"0.7\", features = [\"csr\"] }
gloo-net = { version = \"0.6\" }
").unwrap();
        let pin = Pin { file: "src/catalog.ts".into(), pattern: r#"leptos = \{ version = \"([0-9.]+)\""#.into(), format: "major.minor".into(), max_auto_bump: "minor".into() };
        assert!(apply_pin(dir.path(), &pin, "0.8.3").unwrap());
        let t = std::fs::read_to_string(dir.path().join("src/catalog.ts")).unwrap();
        assert!(t.contains("leptos = { version = \"0.8\", features") && t.contains("gloo-net = { version = \"0.6\" }"), "{t}");
        assert!(!apply_pin(dir.path(), &pin, "0.8.9").unwrap(), "same major.minor: nothing to change");
        let bad = Pin { pattern: r"nothing like this\(([0-9]+)\)".into(), ..pin.clone() };
        assert!(apply_pin(dir.path(), &bad, "1.0.0").is_err());
    }

    #[test]
    fn writes_into_docs_upstream() {
        let dir = tempfile::tempdir().unwrap();
        let rel = write_plan(dir.path(), &ctx("x")).unwrap();
        assert_eq!(rel, PathBuf::from("docs").join("upstream").join("poem").join("3.2.0.md"));
        assert!(dir.path().join(rel).exists());
    }
}
